"""JWT tokens with kind and scopes claims for slurm-quota-serve."""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any, Literal

import jwt
from rfl.authentication.errors import JWTDecodeError
from rfl.authentication.jwt import JWTBaseManager, JWTManager
from rfl.authentication.user import AuthenticatedUser

TokenKind = Literal["user", "application"]

TOKEN_KINDS: tuple[TokenKind, ...] = ("user", "application")


def unverified_claims(token: str) -> dict[str, Any]:
    """Return the claims of a token without verifying it, for tokens just
    generated by this service."""
    return jwt.decode(token, options={"verify_signature": False})


class TokenUser(AuthenticatedUser):
    """Authenticated user with the kind and scopes of the token.

    Scopes are None when the token has no scopes claim, its access is then
    restricted by the role of its owner only.
    """

    def __init__(
        self,
        login: str,
        groups: list[str],
        *,
        kind: TokenKind = "user",
        scopes: Iterable[str] | None = None,
        jti: str | None = None,
    ) -> None:
        super().__init__(login=login, groups=groups)
        self.kind: TokenKind = kind
        self.scopes = None if scopes is None else frozenset(scopes)
        self.jti = jti


class SlurmQuotaJWTManager(JWTManager):
    """JWT manager that decodes the kind (typ), scopes and jti claims of tokens
    and generates application tokens with these claims.

    User tokens are generated by RFL JWTManager.generate(), without these
    claims.
    """

    def decode(self, token: str) -> TokenUser:
        payload: dict[str, Any] = JWTBaseManager.decode(
            self, token, audience=self.audience
        )
        kind = payload.get("typ", "user")
        if kind not in TOKEN_KINDS:
            raise JWTDecodeError(f"Token type {kind} is invalid")
        scopes = payload.get("scopes")
        if scopes is not None and (
            not isinstance(scopes, list)
            or not all(isinstance(scope, str) for scope in scopes)
        ):
            raise JWTDecodeError("Token scopes are invalid")
        jti = payload.get("jti")
        if kind == "application":
            if not isinstance(jti, str):
                raise JWTDecodeError("Application token has no identifier")
            if scopes is None:
                raise JWTDecodeError("Application token has no scopes")
        return TokenUser(
            login=payload["sub"],
            groups=payload.get("groups", []),
            kind=kind,
            scopes=scopes,
            jti=jti if kind == "application" else None,
        )

    def generate_application(
        self,
        user: AuthenticatedUser,
        duration: int,
        jti: str,
        scopes: Iterable[str],
    ) -> str:
        """Return an application token valid for duration days with the given
        identifier and scopes."""
        return JWTBaseManager.generate(
            self,
            duration,
            {
                "aud": self.audience,
                "sub": user.login,
                "groups": user.groups,
                "typ": "application",
                "jti": jti,
                "scopes": sorted(set(scopes)),
            },
        )
